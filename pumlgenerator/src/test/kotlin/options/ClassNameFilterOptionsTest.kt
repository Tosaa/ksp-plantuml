package options

import ClassNameFilter
import CompilationTest
import Options
import assertContainsNot
import com.tschuchort.compiletesting.KotlinCompilation
import com.tschuchort.compiletesting.SourceFile
import com.tschuchort.compiletesting.sourcesGeneratedBySymbolProcessor
import org.jetbrains.kotlin.compiler.plugin.ExperimentalCompilerApi
import kotlin.test.Test
import kotlin.test.assertContains
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertFalse
import kotlin.test.assertTrue

class ClassNameFilterOptionsTest : CompilationTest() {

    private val generatedLookingCode = """
    package app
    class MainViewModel
    class Hilt_MainActivity
    class MainViewModel_Factory
    class AppDao_Impl
    """

    @Test
    fun `filter rules match prefix suffix and contains`() {
        val filter = ClassNameFilter(
            excludedExact = listOf("Exact"),
            excludedPrefixes = listOf("Hilt_"),
            excludedSuffixes = listOf("_Factory"),
            excludedContains = listOf("_HiltModules"),
        )
        assertFalse(filter.shouldInclude("Exact"))
        assertFalse(filter.shouldInclude("Hilt_MainActivity"))
        assertFalse(filter.shouldInclude("MainViewModel_Factory"))
        assertFalse(filter.shouldInclude("MainViewModel_HiltModules_KeyModule"))
        assertTrue(filter.shouldInclude("MainViewModel"))
    }

    @Test
    fun `preset ANDROID_GENERATED excludes framework generated class names`() {
        val filter = ClassNameFilter.fromPresetName("ANDROID_GENERATED")
        assertFalse(filter.shouldInclude("Hilt_MainActivity"))
        assertFalse(filter.shouldInclude("MainViewModel_Factory"))
        assertFalse(filter.shouldInclude("AppDao_Impl"))
        assertFalse(filter.shouldInclude("AppModule_ProvideDatabaseFactory"))
        assertTrue(filter.shouldInclude("MainViewModel"))
    }

    @Test
    fun `preset HILT_DAGGER excludes the class names that are generated by Hilt and Dagger only`() {
        val filter = ClassNameFilter.fromPresetName("HILT_DAGGER")
        assertFalse(filter.shouldInclude("Hilt_MainActivity"))
        assertFalse(filter.shouldInclude("MainViewModel_Factory"))
        assertFalse(filter.shouldInclude("MainActivity_MembersInjector"))
        assertFalse(filter.shouldInclude("MainViewModel_HiltModules_KeyModule_ProvideFactory"))
        assertFalse(filter.shouldInclude("AppModule_ProvideDatabaseFactory"))
        assertTrue(filter.shouldInclude("AppDao_Impl"))
        assertTrue(filter.shouldInclude("ActivityMainBinding"))
        assertTrue(filter.shouldInclude("MainViewModel"))
    }

    @Test
    fun `preset ROOM excludes the class names that are generated by Room only`() {
        val filter = ClassNameFilter.fromPresetName("ROOM")
        assertFalse(filter.shouldInclude("AppDao_Impl"))
        assertFalse(filter.shouldInclude("AppDatabase_Impl"))
        assertTrue(filter.shouldInclude("Hilt_MainActivity"))
        assertTrue(filter.shouldInclude("AppDao"))
    }

    @Test
    fun `the name of a preset is not case sensitive and a blank name selects no preset`() {
        assertEquals(ClassNameFilter.HILT_DAGGER, ClassNameFilter.fromPresetName("hilt_dagger"))
        assertEquals(ClassNameFilter.ROOM, ClassNameFilter.fromPresetName(" Room "))
        assertEquals(ClassNameFilter.NONE, ClassNameFilter.fromPresetName(""))
        assertEquals(ClassNameFilter.NONE, Options(mapOf("puml.filterPreset" to " ")).classNameFilter)
    }

    @Test
    fun `an unknown preset is reported when the options are created`() {
        val exception = assertFailsWith<IllegalArgumentException> { Options(filterPreset = "HILT") }
        assertContains(exception.message.orEmpty(), "puml.filterPreset")
        assertContains(exception.message.orEmpty(), "HILT_DAGGER")
    }

    @Test
    fun `explicit exclusions are combined with the preset`() {
        val filter = Options(filterPreset = "ROOM", excludedClassNames = listOf("Exact"), excludedClassNamePrefixes = listOf("Fake")).classNameFilter
        assertFalse(filter.shouldInclude("AppDao_Impl"))
        assertFalse(filter.shouldInclude("Exact"))
        assertFalse(filter.shouldInclude("FakeRepository"))
        assertTrue(filter.shouldInclude("Repository"))
    }

    @OptIn(ExperimentalCompilerApi::class)
    @Test
    fun `filterPreset option removes generated classes from the diagram`() {
        val compilation = newCompilation(
            Options(filterPreset = "ANDROID_GENERATED"),
            listOf(SourceFile.kotlin("App.kt", generatedLookingCode))
        )
        val result = compilation.compile()
        assertEquals(KotlinCompilation.ExitCode.OK, result.exitCode, result.messages)
        val generatedFile = result.sourcesGeneratedBySymbolProcessor.first().readText()
        assertContains(generatedFile, "\"MainViewModel\" as app_MainViewModel")
        assertContainsNot(generatedFile, "Hilt_MainActivity")
        assertContainsNot(generatedFile, "MainViewModel_Factory")
        assertContainsNot(generatedFile, "AppDao_Impl")
    }

    @OptIn(ExperimentalCompilerApi::class)
    @Test
    fun `explicit exclusion lists remove matching classes from the diagram`() {
        val compilation = newCompilation(
            Options(excludedClassNameSuffixes = listOf("ViewModel")),
            listOf(SourceFile.kotlin("App.kt", generatedLookingCode))
        )
        val result = compilation.compile()
        assertEquals(KotlinCompilation.ExitCode.OK, result.exitCode, result.messages)
        val generatedFile = result.sourcesGeneratedBySymbolProcessor.first().readText()
        assertContainsNot(generatedFile, "\"MainViewModel\" as app_MainViewModel")
        assertContains(generatedFile, "Hilt_MainActivity")
    }

    @OptIn(ExperimentalCompilerApi::class)
    @Test
    fun `prefixes and fragments remove matching classes from the diagram`() {
        val compilation = newCompilation(
            Options(excludedClassNamePrefixes = listOf("Hilt_"), excludedClassNameContains = listOf("Dao")),
            listOf(SourceFile.kotlin("App.kt", generatedLookingCode))
        )
        val result = compilation.compile()
        assertEquals(KotlinCompilation.ExitCode.OK, result.exitCode, result.messages)
        val generatedFile = result.sourcesGeneratedBySymbolProcessor.first().readText()
        assertContains(generatedFile, "\"MainViewModel\" as app_MainViewModel")
        assertContains(generatedFile, "MainViewModel_Factory")
        assertContainsNot(generatedFile, "Hilt_MainActivity")
        assertContainsNot(generatedFile, "AppDao_Impl")
    }

    @OptIn(ExperimentalCompilerApi::class)
    @Test
    fun `type aliases are excluded by the same rules as classes`() {
        val code = """
        package app
        class MainViewModel
        typealias GeneratedViewModel = MainViewModel
        typealias ViewModel = MainViewModel
        """
        val compilation = newCompilation(Options(excludedClassNamePrefixes = listOf("Generated")), listOf(SourceFile.kotlin("App.kt", code)))
        val result = compilation.compile()
        assertEquals(KotlinCompilation.ExitCode.OK, result.exitCode, result.messages)
        val generatedFile = result.sourcesGeneratedBySymbolProcessor.first().readText()
        assertContains(generatedFile, "\"ViewModel\" as app_ViewModel")
        assertContainsNot(generatedFile, "GeneratedViewModel")
    }
}

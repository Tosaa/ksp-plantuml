/**
 * Excludes classes from the diagram by their simple name.
 *
 * A class is excluded if its name is listed in [excludedExact], starts with one of the [excludedPrefixes],
 * ends with one of the [excludedSuffixes] or contains one of the [excludedContains].
 */
data class ClassNameFilter(
    val excludedExact: List<String> = emptyList(),
    val excludedPrefixes: List<String> = emptyList(),
    val excludedSuffixes: List<String> = emptyList(),
    val excludedContains: List<String> = emptyList(),
) {
    /**
     * @return `true` if a class with the given simple name is not excluded by this filter
     */
    fun shouldInclude(simpleName: String): Boolean = simpleName !in excludedExact &&
            excludedPrefixes.none { simpleName.startsWith(it) } &&
            excludedSuffixes.none { simpleName.endsWith(it) } &&
            excludedContains.none { simpleName.contains(it) }

    /**
     * @return a filter that excludes every class that is excluded by this filter or by [other]
     */
    operator fun plus(other: ClassNameFilter): ClassNameFilter = ClassNameFilter(
        excludedExact = excludedExact + other.excludedExact,
        excludedPrefixes = excludedPrefixes + other.excludedPrefixes,
        excludedSuffixes = excludedSuffixes + other.excludedSuffixes,
        excludedContains = excludedContains + other.excludedContains,
    )

    companion object {

        /** Excludes nothing. */
        val NONE = ClassNameFilter()

        /**
         * Classes generated by Hilt and Dagger.
         * They are generated into the package of the class they belong to, therefore they cannot be excluded by their package.
         */
        val HILT_DAGGER = ClassNameFilter(
            excludedPrefixes = listOf(
                "Hilt_", // Hilt_MainActivity
            ),
            excludedSuffixes = listOf(
                "_Factory", // MainViewModel_Factory
                "_MembersInjector", // MainActivity_MembersInjector
                "_GeneratedInjector", // MainActivity_GeneratedInjector
                "_AssistedFactory",
                "InstanceHolder", // MainViewModel_Factory.InstanceHolder
            ),
            excludedContains = listOf(
                "_HiltModules", // MainViewModel_HiltModules, MainViewModel_HiltModules_KeyModule_ProvideFactory
                "_HiltComponents", // MainApplication_HiltComponents
                "_Provide", // AppModule_ProvideDatabaseFactory
            ),
        )

        /** Implementations generated by Room. */
        val ROOM = ClassNameFilter(
            excludedSuffixes = listOf(
                "Dao_Impl", // UserDao_Impl
                "Database_Impl", // AppDatabase_Impl
            ),
        )

        /** [HILT_DAGGER] and [ROOM] together with the classes generated by view binding. */
        val ANDROID_GENERATED = HILT_DAGGER + ROOM + ClassNameFilter(
            excludedSuffixes = listOf(
                "Binding", // ActivityMainBinding
            ),
        )

        /** The filters that can be selected by their name with the option `puml.filterPreset`. */
        val PRESETS: Map<String, ClassNameFilter> = mapOf(
            "NONE" to NONE,
            "HILT_DAGGER" to HILT_DAGGER,
            "ROOM" to ROOM,
            "ANDROID_GENERATED" to ANDROID_GENERATED,
        )

        /**
         * @param name name of one of the [PRESETS], the case is ignored and a blank name selects [NONE]
         * @throws IllegalArgumentException if there is no preset with the given name
         */
        fun fromPresetName(name: String): ClassNameFilter {
            val presetName = name.trim().uppercase().ifEmpty { "NONE" }
            return requireNotNull(PRESETS[presetName]) {
                "Unknown puml.filterPreset '$name'. Available presets: ${PRESETS.keys.joinToString()}"
            }
        }
    }
}

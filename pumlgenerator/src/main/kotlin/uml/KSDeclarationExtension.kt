package uml

import com.google.devtools.ksp.processing.KSPLogger
import com.google.devtools.ksp.symbol.ClassKind
import com.google.devtools.ksp.symbol.FileLocation
import com.google.devtools.ksp.symbol.KSClassDeclaration
import com.google.devtools.ksp.symbol.KSDeclaration
import com.google.devtools.ksp.symbol.KSFunctionDeclaration
import com.google.devtools.ksp.symbol.KSPropertyDeclaration
import com.google.devtools.ksp.symbol.KSTypeAlias
import com.google.devtools.ksp.symbol.Modifier
import com.google.devtools.ksp.symbol.Origin
import w

private val SOURCE_ORIGINS = setOf(Origin.KOTLIN, Origin.JAVA)

private val JVM_ROOT_CLASS_NAMES = setOf("java.lang.Object", "java.lang.Enum", "kotlin.Any", "kotlin.Enum")

private val JVM_ROOT_FUNCTION_NAMES = setOf("clone", "finalize", "getClass", "notify", "notifyAll", "wait", "getDeclaringClass", "describeConstable")

private val ENUM_GENERATED_PROPERTY_NAMES = setOf("name", "ordinal", "entries")

private val ENUM_GENERATED_FUNCTION_NAMES = setOf("values", "valueOf")

private val DATA_CLASS_COMPONENT_FUNCTION_NAME = Regex("component\\d+")

/**
 * `true` if this [KSDeclaration] is written in the source code, `false` if it is inherited from a library or generated by the compiler.
 */
private val KSDeclaration.isDeclaredInSource: Boolean
    get() = origin in SOURCE_ORIGINS

/**
 * Checks if this [KSFunctionDeclaration] is one of the functions that every class inherits from `java.lang.Object` or every enum from `java.lang.Enum`, like `getClass` or `wait`.
 * A function with the same name that is declared in the source code, like `fun notify(message: String)`, is not one of them.
 */
internal fun KSFunctionDeclaration.isJvmRootFunction(): Boolean {
    if (simpleName.asString() !in JVM_ROOT_FUNCTION_NAMES || isDeclaredInSource) {
        return false
    }
    val declaringClass = parentDeclaration as? KSClassDeclaration ?: return true
    // Some functions of java.lang.Enum, like getDeclaringClass, are reported as functions of the enum class that inherits them
    return declaringClass.isDeclaredInSource || declaringClass.qualifiedName?.asString() in JVM_ROOT_CLASS_NAMES
}

/**
 * Checks if this [KSPropertyDeclaration] is added by the compiler to the [declarationOwner]: `name`, `ordinal` and `entries` of an enum class.
 */
internal fun KSPropertyDeclaration.isGeneratedMemberOf(declarationOwner: KSClassDeclaration): Boolean {
    return !isDeclaredInSource && declarationOwner.classKind == ClassKind.ENUM_CLASS && simpleName.asString() in ENUM_GENERATED_PROPERTY_NAMES
}

/**
 * Checks if this [KSFunctionDeclaration] is added by the compiler to the [declarationOwner]: `values` and `valueOf` of an enum class, `copy` and `componentN` of a data class.
 * A function with the same name that is declared in the source code, like an overload of `copy`, is not one of them.
 */
internal fun KSFunctionDeclaration.isGeneratedMemberOf(declarationOwner: KSClassDeclaration): Boolean {
    if (isDeclaredInSource) {
        return false
    }
    val name = simpleName.asString()
    return when {
        declarationOwner.classKind == ClassKind.ENUM_CLASS -> name in ENUM_GENERATED_FUNCTION_NAMES
        declarationOwner.modifiers.contains(Modifier.DATA) -> name == "copy" || DATA_CLASS_COMPONENT_FUNCTION_NAME.matches(name)
        else -> false
    }
}

/**
 * Identifies this [KSDeclaration] by its position in the source code.
 * In contrast to the declaration itself, the position is the same in every processing round.
 */
internal val KSDeclaration.sourcePosition: String
    get() {
        val location = location as? FileLocation
        return "${location?.filePath ?: containingFile?.filePath}:${location?.lineNumber}:${qualifiedName?.asString() ?: simpleName.asString()}"
    }

val KSClassDeclaration.fullQualifiedName: String
    get() = "${qualifiedName?.getQualifier() ?: packageName.asString()}.${simpleName.asString()}"

val KSClassDeclaration.className: String
    get() = fullQualifiedName.replace(packageName.asString(), "").trim('.')

val KSTypeAlias.fullQualifiedName: String
    get() = "${qualifiedName?.getQualifier() ?: packageName.asString()}.${simpleName.asString()}"

val KSTypeAlias.shortName: String
    get() = fullQualifiedName.replace(packageName.asString(), "").trim('.')

/**
 * Checks if this [KSFunctionDeclaration] has the modifier [Modifier.OVERRIDE]. If that is the case, the function is inherited.
 *
 * Otherwise:
 * Checks inheritance by comparing all functions of superType classes of [declarationOwner].
 * Internally the name and the return type and the parameter names and types of the functions are compared. This calls expensive operation [com.google.devtools.ksp.symbol.KSTypeReference.resolve]
 * @return `true` if the checked [KSFunctionDeclaration] is probably inherited
 */
internal fun KSFunctionDeclaration.isInheritedFunction(declarationOwner: KSClassDeclaration, logger: KSPLogger? = null): Boolean {
    if (declarationOwner.isCompanionObject) {
        return (declarationOwner.parentDeclaration as? KSClassDeclaration)?.let {
            logger.w { "isInheritedField(): owner was companion object -> resolve base class and call isInheritedField on it: $it" }
            isInheritedFunction(it, logger)
        } ?: run {
            logger.w { "isInheritedField(): owner was companion object but base class could not be resolved" }
            false
        }
    }

    if (declarationOwner.modifiers.contains(Modifier.DATA)) {
        if (this.simpleName.asString().contains(Regex("component\\d"))) {
            // For Data class destruction `componentN()` functions are generated and marked as Override, therefore this special case has to be handled here
            return false
        }
    }

    if (this.modifiers.contains(Modifier.OVERRIDE)) {
        return true
    }

    val superTypesOfDeclarationOwner = declarationOwner.superTypes.toList().mapNotNull { it.resolve().declaration as? KSClassDeclaration }
        .filter { it.qualifiedName?.asString() != "kotlin.Enum" } // Ensures that all Enums have enum specific properties and functions

    val potentialMatchingDeclarations = superTypesOfDeclarationOwner.flatMap { (it.getAllFunctions() + it.declarations.filterIsInstance<KSFunctionDeclaration>()).distinct() }
        .filter { it.simpleName.getShortName() == this.simpleName.getShortName() }
    return if (potentialMatchingDeclarations.isEmpty()) {
        false
    } else {
        potentialMatchingDeclarations.any {
            when {
                it == this -> return true
                it.returnType?.resolve() != this.returnType?.resolve() -> false
                it.parameters.map { it.name?.getShortName() to it.type.resolve() } != this.parameters.map { it.name?.getShortName() to it.type.resolve() } -> false
                else -> true
            }
        }
    }
}

/**
 * Checks if this [KSPropertyDeclaration] has the modifier [Modifier.OVERRIDE]. If that is the case, the property is inherited.
 *
 * Otherwise:
 * Checks inheritance by comparing all properties of superType classes of [declarationOwner].
 * Internally the name and the return type of the properties are compared. This calls expensive operation [com.google.devtools.ksp.symbol.KSTypeReference.resolve]
 * @return `true` if the checked [KSPropertyDeclaration] is probably inherited
 */
internal fun KSPropertyDeclaration.isInheritedProperty(declarationOwner: KSClassDeclaration, logger: KSPLogger? = null): Boolean {
    if (declarationOwner.isCompanionObject) {
        return (declarationOwner.parentDeclaration as? KSClassDeclaration)?.let {
            logger.w { "isInheritedField(): owner was companion object -> resolve base class and call isInheritedField on it: $it" }
            isInheritedProperty(it, logger)
        } ?: run {
            logger.w { "isInheritedField(): owner was companion object but base class could not be resolved" }
            false
        }
    }

    if (this.modifiers.contains(Modifier.OVERRIDE)) {
        return true
    }

    val superTypesOfDeclarationOwner = declarationOwner.superTypes.toList().mapNotNull { it.resolve().declaration as? KSClassDeclaration }
        .filter { it.qualifiedName?.asString() != "kotlin.Enum" } // Ensures that all Enums have enum specific properties and functions

    val potentialMatchingDeclarations = superTypesOfDeclarationOwner.flatMap { (it.getAllProperties() + it.declarations.filterIsInstance<KSPropertyDeclaration>()).distinct() }
        .filter { it.simpleName.getShortName() == this.simpleName.getShortName() }
    return if (potentialMatchingDeclarations.isEmpty()) {
        false
    } else {
        potentialMatchingDeclarations.any {
            when {
                it == this -> true
                it.type.resolve() != this.type.resolve() -> false
                else -> true
            }
        }
    }
}
